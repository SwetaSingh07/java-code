//Write a program to declare, initialize, utilise and print different data types in Java
package assignment.module1;

public class Assignment_02 {

	public static void main(String[] args) {
		byte a=2;//declaration and initialization
		System.out.println(a);//utilization
		short b=-982;//declaration and initialization
		System.out.println(b);//utilization
		int c= 25;//declaration and initialization
		System.out.println(c);//utilization
		long d= 85797678l;//declaration and initialization
		System.out.println(d);//utilization
		float e= 785.20f;//declaration and initialization
		System.out.println(e);//utilization
		double f= 856.797678654;//declaration and initialization
		System.out.println(f);//utilization
		char h= 'S';//declaration and initialization
		System.out.println(h);//utilization
		boolean i= true;//declaration and initialization
		System.out.println(i);//utilization
		String j= "Sweta Singh";//declaration and initialization
		System.out.println(j);//utilization
	}

}
